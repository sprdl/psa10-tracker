#!/usr/bin/env python3
"""
Focus watch (2026-10-18): a few watched cards whose buy window you don't want to miss. After every price check
(full or quick) this reports, per focus card, how the lowest PSA10 ask moved, how many sales there were and at what
prices, how deep the cheap end of the book is, and a status: BUY WINDOW / CLOSE / TURNING / DRIFTING DOWN / FLAT.

    python3 scripts/focus.py add <snkrdunk id> [--until YYYY-MM-DD] [--note TEXT] [--no-push]
    python3 scripts/focus.py remove <snkrdunk id> [--no-push]
    python3 scripts/focus.py list
    python3 scripts/focus.py report            # print the block (full_update.py / quick_update.py print it after publishing)

Files:
  data/focus.json         the focus cards, {"cards": {url: {since, until, note}}}; edited with this script
  data/focus_report.json  generated by build() on every publish (build_history.py calls it), read by the site's
                          Overview "Focus watch" panel and the card page

The target is the card's limit (data/limits.json), else its Buy tier. Rules for the status (first that applies):
  BUY WINDOW     lowest ask ≤ target
  CLOSE          lowest ask within CLOSE_PCT of the target, or a sale at/below the target in the last 24 h
  TURNING        lowest ask ≥ TURN_PCT above its 7-day low and the last 24 h's sales median ≥ the prior 7 days' median
  DRIFTING DOWN  lowest ask ≥ DRIFT_PCT under its level 7 days ago
  FLAT           otherwise
Extra flags: the cheap end of the book thinning (listings within 3% of the lowest ask down ≥ 40% vs the previous
fresh listings read), an event-rule window for the card's set (data/events.json), the focus expiring.
It's a heads-up, not a prediction: the odds model and the verdict stay the judges of price.
"""
import argparse, json, os, re, subprocess, sys
from datetime import datetime, timedelta, timezone, date
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parent.parent
JST = timezone(timedelta(hours=9))
FILE = "data/focus.json"
REPORT = "data/focus_report.json"
CLOSE_PCT = 2.0
TURN_PCT = 3.0
DRIFT_PCT = 2.0
THIN_DROP = 0.4
STATUS_TEXT = {"buy_window": "BUY WINDOW", "close": "CLOSE", "turning": "TURNING", "drifting": "DRIFTING DOWN",
               "flat": "FLAT", "no_data": "NO DATA"}


def _load(root, rel, default):
    p = Path(root) / rel
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def _ts(s):
    return datetime.fromisoformat(s)


def _url(sid):
    sid = str(sid).strip().rstrip("/").split("/")[-1]
    if not sid.isdigit():
        sys.exit(f"Not a SNKRDUNK id: {sid}")
    return f"https://snkrdunk.com/apparels/{sid}"


def set_code(name):
    m = re.search(r"\[([A-Za-z0-9-]+)\s", name or "")
    return m.group(1) if m else None


def short_name(name):
    return (name or "").split("[")[0].strip() + ((" " + re.search(r"\[([^\]]+)\]", name).group(1)) if name and "[" in name else "")


def _snap_cards(root, file):
    d = _load(root, f"data/snapshots/{file}", None)
    return d, {c["url"]: c for c in (d or {}).get("cards", [])}


def _listings(card):
    g = ((card or {}).get("grades") or {}).get("psa10") or {}
    lst = [p for p in (g.get("top20_cheapest_listings") or []) if isinstance(p, (int, float))]
    return lst, g.get("listings_as_of")


def _event_flags(root, code, now):
    ev = _load(root, "data/events.json", {})
    win = ev.get("window_days", 3)
    out = []
    for e in ev.get("events", []):
        if not e.get("d") or not e.get("major") or e.get("tentative"):
            continue
        scope = e.get("scope")
        if scope != "all" and code not in (scope or []):
            continue
        d = date.fromisoformat(e["d"])
        days = (d - now.date()).days
        if 0 <= days <= win:
            out.append({"level": "warn", "text": f"Event rule window: {e['name'][:40]} on {d:%m/%d}: release dips average about −2% over the next 4 days"})
        elif -4 <= days < 0:
            out.append({"level": "info", "text": f"Just after the {d:%m/%d} release: the usual post-release dip window (about 4 days)"})
        elif win < days <= 14:
            out.append({"level": "info", "text": f"{e['name'][:40]} on {d:%m/%d} ({days} days): the event rule starts {d - timedelta(days=win):%m/%d}"})
    return out


def card_report(root, url, meta, hist, sales_all, manifest, limits):
    snaps = hist.get("snapshots", [])
    pts = []
    for s in snaps:
        r = (s.get("r") or {}).get(url)
        p = (s.get("p") or {}).get(url)
        ask = r[0] if r and r[0] else (p[0] if p else None)
        if ask:
            pts.append((_ts(s["d"]), ask))
    files = [m["file"] for m in manifest.get("snapshots", []) if m.get("file")]
    latest_d, latest = _snap_cards(root, files[-1]) if files else (None, {})
    card = latest.get(url)
    name = (card or {}).get("card_name_ja") or meta.get("name") or url
    out = {"url": url, "id": url.rsplit("/", 1)[-1], "name": name, "short": short_name(name),
           "image_url": (card or {}).get("image_url"), "since": meta.get("since"), "until": meta.get("until"),
           "note": meta.get("note")}
    tiers = (((card or {}).get("analysis") or {}).get("tiers")) or {}
    lim = ((limits.get("limits") or {}).get(url) or {}).get("price")
    target = lim or tiers.get("buy_upper")
    out.update({"limit": lim, "tiers": tiers or None, "target": target, "target_is": "limit" if lim else ("Buy tier" if target else None)})
    if not pts:
        out.update({"status": "no_data", "headline": "No price yet for this card in the checks.", "flags": []})
        return out
    now_t, ask = pts[-1]
    prev = pts[-2] if len(pts) > 1 else None

    def ask_at(hours):
        cut = now_t - timedelta(hours=hours)
        older = [a for t, a in pts if t <= cut]
        return older[-1] if older else None

    week = [a for t, a in pts if t >= now_t - timedelta(days=7)]
    out.update({"checked": now_t.isoformat(), "ask": ask, "ask_prev": prev[1] if prev else None,
                "prev_checked": prev[0].isoformat() if prev else None,
                "ask_24h": ask_at(24), "ask_7d": ask_at(24 * 7), "low_7d": min(week), "high_7d": max(week)})

    # sales: [hour since epoch UTC, price], the middle of the window the timestamp allows
    sales = [(datetime.fromtimestamp(h * 3600, tz=timezone.utc).astimezone(JST), p) for h, p in sales_all.get(url, [])]
    sales.sort()

    def window(a, b):
        return [p for t, p in sales if a < t <= b]

    since_prev = window(prev[0], now_t + timedelta(hours=1)) if prev else []
    h24 = window(now_t - timedelta(hours=24), now_t + timedelta(hours=1))
    d7 = window(now_t - timedelta(days=7), now_t + timedelta(hours=1))
    prior7 = window(now_t - timedelta(days=8), now_t - timedelta(hours=24))
    out["sales"] = {
        "since_prev": since_prev,
        "h24": {"n": len(h24), "min": min(h24) if h24 else None, "median": median(h24) if h24 else None},
        "d7": {"n": len(d7), "per_day": round(len(d7) / 7, 1), "median": median(d7) if d7 else None,
               "min": min(d7) if d7 else None},
        "prior7_median": median(prior7) if prior7 else None,
        "last": [[t.isoformat(timespec="minutes"), p] for t, p in sales[-8:]],
    }

    # depth: the cheap end of the book, from the latest fresh listings read and the one before it
    depth = None
    lst, as_of = _listings(card)
    if lst:
        lo = min(lst)
        depth = {"as_of": as_of or (latest_d or {}).get("collected_at_jst"), "n": len(lst),
                 "within3": sum(1 for p in lst if p <= lo * 1.03), "within15": sum(1 for p in lst if p <= lo * 1.15),
                 "at_target": sum(1 for p in lst if target and p <= target)}
        cur_as_of = depth["as_of"]
        for f in reversed(files[:-1]):
            d, cs = _snap_cards(root, f)
            pl, pas = _listings(cs.get(url))
            pas = pas or (d or {}).get("collected_at_jst")
            if pl and pas != cur_as_of:
                plo = min(pl)
                depth["prev_as_of"] = pas
                depth["prev_within3"] = sum(1 for p in pl if p <= plo * 1.03)
                depth["prev_lowest"] = plo
                break
    out["depth"] = depth

    # status
    flags = []
    status = "flat"
    gap = (ask / target - 1) * 100 if target else None
    sold_at_target = [p for p in h24 if target and p <= target]
    s24 = out["sales"]["h24"]["median"]
    p7 = out["sales"]["prior7_median"]
    if target and ask <= target:
        status = "buy_window"
    elif (gap is not None and gap <= CLOSE_PCT) or sold_at_target:
        status = "close"
    elif ask >= out["low_7d"] * (1 + TURN_PCT / 100) and s24 and p7 and s24 >= p7:
        status = "turning"
    elif out["ask_7d"] and ask <= out["ask_7d"] * (1 - DRIFT_PCT / 100):
        status = "drifting"
    if sold_at_target:
        flags.append({"level": "go", "text": f"{len(sold_at_target)} sale(s) at ≤¥{target:,} in the last 24 h (lowest ¥{min(sold_at_target):,})"})
    if depth and depth.get("prev_within3", 0) >= 5 and depth["within3"] <= depth["prev_within3"] * (1 - THIN_DROP):
        flags.append({"level": "warn", "text": f"Cheap end thinning: {depth['within3']} asks within 3% of the lowest, down from {depth['prev_within3']}"})
    if depth and depth["within3"] >= 10:
        flags.append({"level": "info", "text": f"Deep wall: {depth['within3']} of {depth['n']} cheapest asks within 3% of the lowest"})
    flags += _event_flags(root, set_code(name), now_t)
    if meta.get("until"):
        left = (date.fromisoformat(meta["until"]) - now_t.date()).days
        if left < 0:
            flags.append({"level": "info", "text": f"Focus ended {meta['until']}: remove it or extend it (scripts/focus.py)"})
        elif left <= 3:
            flags.append({"level": "info", "text": f"Focus ends {meta['until']}"})
    out["status"] = status
    out["gap_pct"] = round(gap, 1) if gap is not None else None
    out["flags"] = flags

    def yen(v):
        return f"¥{v:,.0f}" if v else "–"
    mv = f"{(ask / prev[1] - 1) * 100:+.1f}% since the last check" if prev else "first check"
    wk = f", {(ask / out['ask_7d'] - 1) * 100:+.1f}% over 7 days" if out["ask_7d"] else ""
    tg = f"; {gap:+.1f}% to your {out['target_is']} {yen(target)}" if target and status != "buy_window" else (
        f"; AT/UNDER your {out['target_is']} {yen(target)}" if target else "")
    sp = since_prev
    st = (f"{len(sp)} sale(s) since the last check ({', '.join(yen(p) for p in sp[-5:])})" if sp else "no sales since the last check")
    out["headline"] = f"{yen(ask)} lowest ask ({mv}{wk}){tg}. {st}; {out['sales']['d7']['n']} in 7 days."
    return out


def build(root=ROOT):
    """Write data/focus_report.json (or remove it when no card is in focus). Returns the report or None."""
    root = Path(root)
    focus = _load(root, FILE, {}).get("cards") or {}
    rp = root / REPORT
    if not focus:
        if rp.exists():
            rp.unlink()
        return None
    hist = _load(root, "data/history.json", {})
    sales = (_load(root, "data/sales.json", {}).get("cards")) or {}
    manifest = _load(root, "data/manifest.json", {})
    limits = _load(root, "data/limits.json", {})
    cards = [card_report(root, url, meta or {}, hist, sales, manifest, limits) for url, meta in focus.items()]
    rep = {"about": "Generated by scripts/focus.py on every publish; see its docstring. Edit data/focus.json with focus.py add/remove.",
           "updated": max((c.get("checked") or "" for c in cards), default=None), "cards": cards}
    rp.write_text(json.dumps(rep, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return rep


def print_report(root=ROOT, rep=None):
    """The block the update scripts print after publishing. Its lines go into the run's chat message."""
    rep = rep if rep is not None else _load(root, REPORT, None)
    if not rep or not rep.get("cards"):
        return
    print("\nFOCUS WATCH (put one line per card in the chat message, status first; flags marked ! too):")
    for c in rep["cards"]:
        print(f"  [{STATUS_TEXT.get(c.get('status'), c.get('status'))}] {c['short']}: {c.get('headline', '')}")
        d = c.get("depth")
        if d:
            prev = f" (previous read {d['prev_within3']})" if d.get("prev_within3") is not None else ""
            print(f"      book: {d['within3']} asks within 3%{prev}, {d['within15']} within 15%, {d['at_target']} at/under target")
        for f in c.get("flags", []):
            print(f"      {'!' if f['level'] in ('go', 'warn') else '·'} {f['text']}")


def _push(root, msg, no_push):
    run = lambda *a, check=True: subprocess.run(["git", *a], cwd=root, text=True, capture_output=True, check=check,
                                                env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
    files = [FILE] + ([REPORT] if (Path(root) / REPORT).exists() else [])
    run("add", "-A", *files)
    if run("commit", "-m", msg, check=False).returncode != 0:
        print("Nothing to commit.")
        return
    if no_push:
        print("Committed (not pushed).")
        return
    sys.path.insert(0, str(Path(root) / "scripts"))
    try:
        import deferpush
        if deferpush.active(root):
            print("Committed; the run's last step pushes it.")
            return
    except Exception:
        pass
    p = run("push", check=False)
    print("Pushed." if p.returncode == 0 else "git push failed:\n" + (p.stderr or p.stdout))


def main():
    ap = argparse.ArgumentParser(description="Focus watch: cards reported after every price check")
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("add"); a.add_argument("id"); a.add_argument("--until"); a.add_argument("--note")
    a.add_argument("--no-push", action="store_true")
    r = sub.add_parser("remove"); r.add_argument("id"); r.add_argument("--no-push", action="store_true")
    sub.add_parser("list"); sub.add_parser("report")
    args = ap.parse_args()
    data = _load(ROOT, FILE, {"about": "Focus watch cards (scripts/focus.py). Reported after every price check and on the site's Overview.", "cards": {}})
    data.setdefault("cards", {})
    if args.cmd == "list":
        for u, m in data["cards"].items():
            print(u, m)
        return
    if args.cmd == "report":
        print_report(ROOT, build(ROOT))
        return
    url = _url(args.id)
    if args.cmd == "add":
        if args.until:
            date.fromisoformat(args.until)
        m = data["cards"].get(url, {})
        m.setdefault("since", datetime.now(JST).date().isoformat())
        if args.until:
            m["until"] = args.until
        if args.note:
            m["note"] = args.note
        data["cards"][url] = m
        msg = f"focus: watch {url.rsplit('/', 1)[-1]}"
    else:
        if url not in data["cards"]:
            sys.exit(f"{url} isn't in focus.")
        del data["cards"][url]
        msg = f"focus: stop watching {url.rsplit('/', 1)[-1]}"
    (ROOT / FILE).write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print_report(ROOT, build(ROOT))
    _push(ROOT, msg, args.no_push)


if __name__ == "__main__":
    main()
